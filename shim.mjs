// ============================================================
// shim.mjs — auto-inject gateway env for CLIs launched outside the wrapper
//
// PROBLEM
//   `switch on` writes env.sh and cleans ~/.claude/settings.json (so Claude Code doesn't
//   show the "custom API" banner). Consequence: a `claude` session started from a shell
//   that has NOT sourced env.sh will lack ANTHROPIC_BASE_URL and call
//   api.anthropic.com directly — bypassing the gateway (loses Healer, 1M, pooled quota).
//   Exactly the case of `claude --resume` reopening an old session in a clean shell.
//
// FIX
//   Install executable shims into ~/.llm-switcher/bin/ (placed BEFORE the real binary
//   in PATH). The shim sources env.sh then execs the real binary, so EVERY `claude`
//   /`codex` invocation — including --resume, including from shells without env — goes
//   through the gateway. Doesn't touch settings.json => no banner.
//
// SAFETY
//   - The shim finds the real binary by removing the shim directory itself from PATH,
//     so it never calls itself recursively.
//   - If the gateway is OFF (no active.flag) the shim runs the real binary
//     as-is — no forced routing, no blocking the user.
//   - If the real binary isn't found, the shim reports a clear error instead of staying silent.
// ============================================================

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';
import { paths, ROOT_DIR } from './state.mjs';

export const SHIM_DIR = path.join(os.homedir(), '.llm-switcher', 'bin');

// Local model catalog: generated by applyLaunchState from the active profile's
// publicModels, so it holds official OpenAI slugs only. It gives Codex the metadata
// for the names it requests (otherwise the CLI falls back to full-context mode) and
// it is what the /model picker renders — the picker never calls /v1/models.
// Forward slashes: safe for both `if exist` and TOML strings.
export const CODE_X_CATALOG_PATH = ROOT_DIR.replace(/\\/g, '/') + '/model-catalog.json';

// CLIs to wrap. `claude` is the most important case (--resume), codex included for completeness.
export const SHIMMED = ['claude', 'codex'];

const POSIX_TEMPLATE = (name) => `#!/usr/bin/env bash
# Auto-generated by LLM Switcher — DO NOT EDIT.
# Load the gateway env then run the real "${name}", even when the shell hasn't sourced env.sh
# (e.g.: claude --resume reopening an old session in a clean terminal).
SWITCHER_DIR="${ROOT_DIR}"
SHIM_DIR="\${BASH_SOURCE%/*}"

# Only load env when the gateway is on; when off, let the CLI run as-is.
if [ -f "$SWITCHER_DIR/active.flag" ] && [ -f "$SWITCHER_DIR/env.sh" ]; then
  . "$SWITCHER_DIR/env.sh"
fi

# Find the real binary: drop the shim directory from PATH so it doesn't call itself.
CLEAN_PATH=""
IFS=':'
for p in $PATH; do
  case "$p" in
    "$SHIM_DIR"|"$SHIM_DIR"/) continue ;;
  esac
  [ -z "$p" ] && continue
  if [ -z "$CLEAN_PATH" ]; then CLEAN_PATH="$p"; else CLEAN_PATH="$CLEAN_PATH:$p"; fi
done
unset IFS

REAL="$(PATH="$CLEAN_PATH" command -v ${name} 2>/dev/null)"
if [ -z "$REAL" ]; then
  echo "[llm-switcher] khong tim thay '${name}' that trong PATH (da loai \\$SHIM_DIR)." >&2
  echo "[llm-switcher] go shim: switch shim uninstall" >&2
  exit 127
fi

${name === 'codex' ? `# Codex-only variables (blindfold proxy + CA). The claude shim must not load these.
if [ -f "$SWITCHER_DIR/active.flag" ] && [ -f "$SWITCHER_DIR/env-codex.sh" ]; then
  . "$SWITCHER_DIR/env-codex.sh"
fi

CODEX_SWITCHER_ARGS=()
if [ -n "\${LLM_SWITCHER_CODEX_BASE_URL:-}" ]; then
  CODEX_SWITCHER_ARGS+=(--config "openai_base_url=\${LLM_SWITCHER_CODEX_BASE_URL}")
fi
if [ -f "${CODE_X_CATALOG_PATH}" ]; then
  CODEX_SWITCHER_ARGS+=(--config "model_catalog_json=${CODE_X_CATALOG_PATH}")
fi
if [ -n "\${LLM_SWITCHER_CODEX_MAIN_MODEL:-}" ]; then
  CODEX_SWITCHER_ARGS+=(--config "model=\\"\${LLM_SWITCHER_CODEX_MAIN_MODEL}\\"")
fi
if [ -n "\${LLM_SWITCHER_CODEX_REVIEW_MODEL:-}" ]; then
  CODEX_SWITCHER_ARGS+=(--config "review_model=\\"\${LLM_SWITCHER_CODEX_REVIEW_MODEL}\\"")
fi
if [ -n "\${LLM_SWITCHER_CODEX_SUBAGENT_MODEL:-}" ]; then
  CODEX_SWITCHER_ARGS+=(--config "agents.default_subagent_model=\\"\${LLM_SWITCHER_CODEX_SUBAGENT_MODEL}\\"")
fi
if [ -n "\${LLM_SWITCHER_CODEX_CONTEXT_WINDOW:-}" ]; then
  CODEX_SWITCHER_ARGS+=(--config "model_context_window=\${LLM_SWITCHER_CODEX_CONTEXT_WINDOW}")
fi
if [ -n "\${LLM_SWITCHER_CODEX_AUTO_COMPACT_LIMIT:-}" ]; then
  CODEX_SWITCHER_ARGS+=(--config "model_auto_compact_token_limit=\${LLM_SWITCHER_CODEX_AUTO_COMPACT_LIMIT}")
fi

exec "$REAL" "\${CODEX_SWITCHER_ARGS[@]}" "$@"` : `exec "$REAL" "$@"`}
`;

const WINDOWS_TEMPLATE = (name) => `@echo off
REM Auto-generated by LLM Switcher - DO NOT EDIT.
set "SWITCHER_DIR=${ROOT_DIR}"
if exist "%SWITCHER_DIR%\\active.flag" if exist "%SWITCHER_DIR%\\env.cmd" call "%SWITCHER_DIR%\\env.cmd"
${name === 'codex' ? `REM Codex-only variables (blindfold proxy + CA). The claude shim must not load these.
if exist "%SWITCHER_DIR%\\active.flag" if exist "%SWITCHER_DIR%\\env-codex.cmd" call "%SWITCHER_DIR%\\env-codex.cmd"
set "CODEX_SWITCHER_ARGS="
if defined LLM_SWITCHER_CODEX_BASE_URL set "CODEX_SWITCHER_ARGS=%CODEX_SWITCHER_ARGS% --config openai_base_url=%LLM_SWITCHER_CODEX_BASE_URL%"
if exist "${CODE_X_CATALOG_PATH}" set "CODEX_SWITCHER_ARGS=%CODEX_SWITCHER_ARGS% --config model_catalog_json=${CODE_X_CATALOG_PATH}"
if defined LLM_SWITCHER_CODEX_MAIN_MODEL set "CODEX_SWITCHER_ARGS=%CODEX_SWITCHER_ARGS% --config model=%LLM_SWITCHER_CODEX_MAIN_MODEL%"
if defined LLM_SWITCHER_CODEX_REVIEW_MODEL set "CODEX_SWITCHER_ARGS=%CODEX_SWITCHER_ARGS% --config review_model=%LLM_SWITCHER_CODEX_REVIEW_MODEL%"
if defined LLM_SWITCHER_CODEX_SUBAGENT_MODEL set "CODEX_SWITCHER_ARGS=%CODEX_SWITCHER_ARGS% --config agents.default_subagent_model=%LLM_SWITCHER_CODEX_SUBAGENT_MODEL%"
if defined LLM_SWITCHER_CODEX_CONTEXT_WINDOW set "CODEX_SWITCHER_ARGS=%CODEX_SWITCHER_ARGS% --config model_context_window=%LLM_SWITCHER_CODEX_CONTEXT_WINDOW%"
if defined LLM_SWITCHER_CODEX_AUTO_COMPACT_LIMIT set "CODEX_SWITCHER_ARGS=%CODEX_SWITCHER_ARGS% --config model_auto_compact_token_limit=%LLM_SWITCHER_CODEX_AUTO_COMPACT_LIMIT%"` : ''}
for /f "delims=" %%i in ('where ${name}.cmd 2^>nul ^| findstr /v /i "\\.llm-switcher\\\\bin"') do (
  call "%%i" ${name === 'codex' ? '%CODEX_SWITCHER_ARGS% ' : ''}%*
  exit /b
)
for /f "delims=" %%i in ('where ${name}.exe 2^>nul ^| findstr /v /i "\\.llm-switcher\\\\bin"') do (
  call "%%i" ${name === 'codex' ? '%CODEX_SWITCHER_ARGS% ' : ''}%*
  exit /b
)
echo [llm-switcher] khong tim thay '${name}' that trong PATH.>&2
exit /b 127
`;

export function renderShim(name, platform = process.platform) {
  return platform === 'win32' ? WINDOWS_TEMPLATE(name) : POSIX_TEMPLATE(name);
}

function shimPath(name) {
  return path.join(SHIM_DIR, process.platform === 'win32' ? `${name}.cmd` : name);
}

/** Install shims for the CLIs. Returns {installed:[], skipped:[], error?} */
export function installShims(names = SHIMMED) {
  try {
    fs.mkdirSync(SHIM_DIR, { recursive: true });
  } catch (err) {
    return { installed: [], skipped: [], error: `khong tao duoc ${SHIM_DIR}: ${err.message}` };
  }

  const installed = [];
  const skipped = [];
  for (const name of names) {
    const target = shimPath(name);
    const body = renderShim(name);
    try {
      // Don't overwrite unfamiliar files created by the user.
      if (fs.existsSync(target)) {
        const cur = fs.readFileSync(target, 'utf8');
        if (!cur.includes('Auto-generated by LLM Switcher')) {
          skipped.push({ name, reason: 'file da ton tai va khong phai shim cua switcher' });
          continue;
        }
      }
      fs.writeFileSync(target, body, 'utf8');
      if (process.platform !== 'win32') fs.chmodSync(target, 0o755);
      installed.push(name);
    } catch (err) {
      skipped.push({ name, reason: err.message });
    }
  }
  return { installed, skipped };
}

export function uninstallShims(names = SHIMMED) {
  const removed = [];
  for (const name of names) {
    const target = shimPath(name);
    try {
      if (!fs.existsSync(target)) continue;
      const cur = fs.readFileSync(target, 'utf8');
      if (!cur.includes('Auto-generated by LLM Switcher')) continue;
      fs.unlinkSync(target);
      removed.push(name);
    } catch {}
  }
  return { removed };
}

/** Is SHIM_DIR already ahead of the real binary in PATH? */
export function shimStatus(names = SHIMMED) {
  const entries = (process.env.PATH || '').split(path.delimiter).filter(Boolean);
  const idx = entries.findIndex(p => path.resolve(p) === path.resolve(SHIM_DIR));
  const out = { dir: SHIM_DIR, onPath: idx !== -1, position: idx, shims: [] };

  for (const name of names) {
    const target = shimPath(name);
    const exists = fs.existsSync(target);
    let effective = null;   // which binary will run when the command name is typed
    for (const p of entries) {
      const cand = path.join(p, process.platform === 'win32' ? `${name}.cmd` : name);
      const candExe = path.join(p, name);
      if (fs.existsSync(cand)) { effective = cand; break; }
      if (fs.existsSync(candExe)) { effective = candExe; break; }
    }
    out.shims.push({
      name,
      installed: exists,
      effective,
      active: exists && effective !== null && path.resolve(effective) === path.resolve(target)
    });
  }
  return out;
}

/** Line to add to the shell rc so the shim comes before the real binary. */
// Windows: setx truncates at 1024 characters and would copy the merged system+user PATH into the
// user key, and PowerShell does not expand %PATH%. Prepend to the User-scope Path only.
export function pathExportLine(platform = process.platform) {
  if (platform === 'win32') {
    return `powershell -NoProfile -Command "[Environment]::SetEnvironmentVariable('Path', '${SHIM_DIR};' + [Environment]::GetEnvironmentVariable('Path', 'User'), 'User')"`;
  }
  return `export PATH="${SHIM_DIR}:$PATH"`;
}

/** Which rc file to edit, based on the current shell. Windows has none: the command above is run once. */
export function suggestedRcFiles(platform = process.platform) {
  if (platform === 'win32') return [];
  const home = os.homedir();
  const shell = path.basename(process.env.SHELL || '');
  if (shell === 'zsh') return [path.join(home, '.zshrc'), path.join(home, '.zprofile')];
  if (shell === 'bash') return [path.join(home, '.bashrc'), path.join(home, '.bash_profile')];
  return [path.join(home, '.profile')];
}

/**
 * Check whether running CLI processes have the gateway env.
 * This is the hardest failure to spot: a `claude` session opened BEFORE the gateway
 * was enabled (or from a shell that hasn't sourced env.sh) will call api.anthropic.com
 * directly. The shim intercepts NEW sessions, but live processes must be detected and reported so they can be restarted.
 */
export function auditRunningProcesses(names = SHIMMED) {
  if (process.platform === 'win32') return { supported: false, procs: [] };
  const procs = [];
  try {
    // Get pid + command of the CLIs of interest (excluding the pgrep/grep command itself).
    const pattern = names.join('|');
    const listed = execFileSync('pgrep', ['-f', `(${pattern})`], { encoding: 'utf8' })
      .split('\n').map(s => s.trim()).filter(Boolean);

    for (const pid of listed) {
      let cmd = '';
      try {
        cmd = execFileSync('ps', ['-p', pid, '-o', 'command='], { encoding: 'utf8' }).trim();
      } catch { continue; }
      if (!cmd) continue;
      // Keep only processes that are actually the CLI under check, skip helper processes.
      if (!names.some(n => new RegExp(`(^|/|\\s)${n}(\\s|$)`).test(cmd))) continue;
      if (/pgrep|llm-switcher\/(switch|proxy)\.mjs/.test(cmd)) continue;

      let hasEnv = null;  // null = cannot read that process's env
      try {
        // `ps eww` prints the environ; only works for the user's own processes.
        const envDump = execFileSync('ps', ['eww', '-p', pid, '-o', 'command='], { encoding: 'utf8' });
        hasEnv = /ANTHROPIC_BASE_URL=/.test(envDump);
      } catch {}
      procs.push({ pid, cmd: cmd.slice(0, 90), hasEnv });
    }
  } catch {
    // pgrep returns a non-zero exit code when there are no processes — not an error.
  }
  return { supported: true, procs };
}

